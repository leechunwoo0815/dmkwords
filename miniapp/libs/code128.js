// Code 128（Code Set B）编码器 — 活动入场券条形码（PRD §9.2.1 门店扫码签到）
//
// 为什么只做 Set B：券码形如 TK00001000022C49（大写字母 + 数字，ASCII 32–126），
// 正好落在 Set B 值域内，不需要 A/C 之间切换，也不需要自动切换逻辑。
// 二维枪两者都能读，条形码是"二维码扫不出时"的备用通道（纸质票/贴纸同样可用）。
//
// 图案表（BARS，107 项：103 个数据码 + 3 个起始码 + 1 个终止码）取自
// jsbarcode@3.12.3 src/barcodes/CODE128/constants.js（MIT），逐字复制未改动——
// 这张表是标准查表数据，不能靠公式推导，抄错一位就扫不出来。
// 校验方式：与 jsbarcode 的 CODE128B 编码器逐位比对（见 miniapp/libs/README.md）。
//
// 输出：'1'=黑条，'0'=空白，从左到右的模块序列。

