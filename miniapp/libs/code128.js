/**
 * 编码为模块串。不可编码的字符（Set B 之外的 ASCII）直接剔除——
 * 券码由后端生成、必然是 ASCII，此处是防御性兜底，不抛错以免扫码枪误输入时整页崩。
 * @param {string} text 券码
 * @returns {string} '1'/'0' 模块串
 */
function encode(text) {
  const clean = String(text || '').toUpperCase().replace(/[^\x20-\x7E]/g, '');
  if (!clean) return '';
  const codes = [START_B];
  for (let i = 0; i < clean.length; i += 1) {
    codes.push(clean.charCodeAt(i) - 32); // Set B：字符值 = ASCII - 32
  }
  let checksum = START_B;
  for (let i = 1; i < codes.length; i += 1) {
    checksum += codes[i] * i; // 起始码权重 1，随后依次 1,2,3…
  }
  codes.push(checksum % MODULO);
  codes.push(STOP);
  return codes.map((c) => String(BARS[c])).join('');
}

module.exports = { encode, START_B, STOP, BARS };
