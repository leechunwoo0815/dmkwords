def seed() -> int:
    db = get_session()
    try:
        existing = {r[0] for r in db.query(DictionaryWord.word).all()}
        added = 0
        for word, phonetic, definition, translation in DICT_SEEDS:
            if word in existing:
                continue
            db.add(
                DictionaryWord(
                    word=word,
                    phonetic=phonetic,
                    definition=definition,
                    translation=translation,
                )
            )
            added += 1
        db.commit()
        return added
    finally:
        db.close()


if __name__ == "__main__":
    print(f"dictionary seeded: +{seed()}")
